#!/usr/bin/env python3
"""
VIDEO COMPOSITING SCRIPT
Combines base video with focus overlay using FFmpeg
"""

import subprocess
import json
import sys
from pathlib import Path


def load_config(config_path: str = "overlay_config.json") -> dict:
    """Load configuration from JSON file."""
    with open(config_path, 'r') as f:
        return json.load(f)


def composite_videos_ffmpeg(
    base_video: str,
    overlay_video: str,
    output_video: str,
    quality: str = "high"
) -> None:
    """
    Composite overlay onto base video using FFmpeg.

    Args:
        base_video: Path to original video
        overlay_video: Path to alpha overlay video
        output_video: Path to output composite video
        quality: 'high', 'medium', or 'fast'
    """

    # Quality presets
    quality_settings = {
        'high': {'crf': 18, 'preset': 'slow'},
        'medium': {'crf': 23, 'preset': 'medium'},
        'fast': {'crf': 28, 'preset': 'fast'}
    }

    settings = quality_settings.get(quality, quality_settings['high'])

    # FFmpeg command for alpha compositing
    cmd = [
        'ffmpeg',
        '-i', base_video,           # Input 1: base video
        '-i', overlay_video,        # Input 2: overlay with alpha
        '-filter_complex',
        '[0:v][1:v]overlay',        # Composite overlay onto base
        '-c:v', 'libx264',          # H.264 codec
        '-crf', str(settings['crf']),
        '-preset', settings['preset'],
        '-c:a', 'copy',             # Copy audio from base video
        '-y',                       # Overwrite output
        output_video
    ]

    print(f"Compositing videos with FFmpeg ({quality} quality)...")
    print(f"Command: {' '.join(cmd)}\n")

    try:
        subprocess.run(cmd, check=True)
        print(f"\n✓ Composite video created: {output_video}")
    except subprocess.CalledProcessError as e:
        print(f"✗ FFmpeg error: {e}")
        sys.exit(1)
    except FileNotFoundError:
        print("✗ FFmpeg not found. Please install FFmpeg:")
        print("  - Ubuntu/Debian: sudo apt install ffmpeg")
        print("  - macOS: brew install ffmpeg")
        print("  - Windows: Download from https://ffmpeg.org/")
        sys.exit(1)


def composite_videos_opencv(
    base_video: str,
    overlay_video: str,
    output_video: str,
    fps: float
) -> None:
    """
    Alternative: Composite using OpenCV (Python-only, no FFmpeg needed).

    Args:
        base_video: Path to original video
        overlay_video: Path to alpha overlay video
        output_video: Path to output composite video
        fps: Frames per second
    """
    import cv2
    import numpy as np

    # Open videos
    base_cap = cv2.VideoCapture(base_video)
    overlay_cap = cv2.VideoCapture(overlay_video)

    # Get video properties
    width = int(base_cap.get(cv2.CAP_PROP_FRAME_WIDTH))
    height = int(base_cap.get(cv2.CAP_PROP_FRAME_HEIGHT))
    total_frames = int(base_cap.get(cv2.CAP_PROP_FRAME_COUNT))

    # Setup writer
    fourcc = cv2.VideoWriter_fourcc(*'mp4v')
    writer = cv2.VideoWriter(output_video, fourcc, fps, (width, height))

    print(f"Compositing {total_frames} frames with OpenCV...")

    frame_num = 0
    while True:
        ret_base, base_frame = base_cap.read()
        ret_overlay, overlay_frame = overlay_cap.read()

        if not ret_base or not ret_overlay:
            break

        # Extract alpha channel from overlay
        if overlay_frame.shape[2] == 4:  # BGRA
            overlay_bgr = overlay_frame[:, :, :3]
            alpha = overlay_frame[:, :, 3:] / 255.0
        else:  # BGR (no alpha)
            overlay_bgr = overlay_frame
            alpha = np.ones((height, width, 1), dtype=np.float32)

        # Alpha blend: result = base * (1 - alpha) + overlay * alpha
        blended = (base_frame * (1 - alpha) + overlay_bgr * alpha).astype(np.uint8)

        writer.write(blended)

        frame_num += 1
        if frame_num % 100 == 0:
            progress = (frame_num / total_frames) * 100
            print(f"  Progress: {progress:.1f}% ({frame_num}/{total_frames})")

    # Cleanup
    base_cap.release()
    overlay_cap.release()
    writer.release()

    print(f"\n✓ Composite video created: {output_video}")


def main():
    """Main compositing workflow."""

    # Load configuration
    try:
        config = load_config()
    except FileNotFoundError:
        print("✗ Configuration file 'overlay_config.json' not found!")
        print("Please create the config file first.")
        sys.exit(1)

    base_video = config['video']['base_video']
    overlay_video = "focus_overlay_alpha.mp4"  # Generated by video_focus_overlay.py
    output_video = config['video']['output_video']
    fps = config['video']['fps']

    # Validate input files
    if not Path(base_video).exists():
        print(f"✗ Base video not found: {base_video}")
        print("Please update 'base_video' path in overlay_config.json")
        sys.exit(1)

    if not Path(overlay_video).exists():
        print(f"✗ Overlay video not found: {overlay_video}")
        print("Please run 'python video_focus_overlay.py' first to generate the overlay.")
        sys.exit(1)

    # Choose compositing method
    print("Select compositing method:")
    print("1. FFmpeg (recommended - faster, better quality)")
    print("2. OpenCV (Python-only, no external dependencies)")
    choice = input("Enter choice (1 or 2): ").strip()

    if choice == "1":
        quality = input("Quality (high/medium/fast) [high]: ").strip() or "high"
        composite_videos_ffmpeg(base_video, overlay_video, output_video, quality)
    elif choice == "2":
        composite_videos_opencv(base_video, overlay_video, output_video, fps)
    else:
        print("Invalid choice. Exiting.")
        sys.exit(1)


if __name__ == "__main__":
    main()
